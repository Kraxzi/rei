/**
 * Generates migrations/0002_seed_reference.sql from the seed data in @rei/core and below.
 * Run: pnpm --filter @rei/api seed:gen
 * Reference data only — no listings, no tax rules (those need a verified source and date).
 */
import { writeFileSync } from 'node:fs';
import { CATEGORIES, FIELD_LIBRARY, TYPES } from '@rei/core';

const q = (v: unknown): string =>
  v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(typeof v === 'string' ? v : JSON.stringify(v)).replaceAll("'", "''")}'`;
const j = (v: unknown) => q(JSON.stringify(v));

const COUNTRIES = [
  { code: 'IT', name: { ru: 'Италия', it: 'Italia', en: 'Italy' }, currency: 'EUR', languages: ['it'] },
  { code: 'DE', name: { ru: 'Германия', it: 'Germania', en: 'Germany' }, currency: 'EUR', languages: ['de'] },
  { code: 'FR', name: { ru: 'Франция', it: 'Francia', en: 'France' }, currency: 'EUR', languages: ['fr'] },
  { code: 'ES', name: { ru: 'Испания', it: 'Spagna', en: 'Spain' }, currency: 'EUR', languages: ['es', 'ca', 'eu', 'gl'] },
  { code: 'AT', name: { ru: 'Австрия', it: 'Austria', en: 'Austria' }, currency: 'EUR', languages: ['de'] },
];

// ISTAT region codes
const IT_REGIONS: Array<[string, string]> = [
  ['01', 'Piemonte'], ['02', "Valle d'Aosta"], ['03', 'Lombardia'], ['04', 'Trentino-Alto Adige'], ['05', 'Veneto'],
  ['06', 'Friuli-Venezia Giulia'], ['07', 'Liguria'], ['08', 'Emilia-Romagna'], ['09', 'Toscana'], ['10', 'Umbria'],
  ['11', 'Marche'], ['12', 'Lazio'], ['13', 'Abruzzo'], ['14', 'Molise'], ['15', 'Campania'], ['16', 'Puglia'],
  ['17', 'Basilicata'], ['18', 'Calabria'], ['19', 'Sicilia'], ['20', 'Sardegna'],
];
// Liguria provinces (first region in scope); others are added in stage 2 from ISTAT open data.
const LIGURIA_PROVINCES: Array<[string, string]> = [['IM', 'Imperia'], ['SV', 'Savona'], ['GE', 'Genova'], ['SP', 'La Spezia']];

const out: string[] = ['-- GENERATED by scripts/gen-seed.ts — do not edit by hand.', ''];

for (const c of COUNTRIES)
  out.push(`INSERT INTO countries (code, name, currency, languages) VALUES (${q(c.code)}, ${j(c.name)}, ${q(c.currency)}, ${j(c.languages)});`);
out.push('');
for (const [code, name] of IT_REGIONS)
  out.push(`INSERT INTO regions (id, country_code, code, name, level) VALUES (${q(`it-r-${code}`)}, 'IT', ${q(code)}, ${q(name)}, 'region');`);
for (const [code, name] of LIGURIA_PROVINCES)
  out.push(`INSERT INTO regions (id, country_code, parent_id, code, name, level) VALUES (${q(`it-p-${code.toLowerCase()}`)}, 'IT', 'it-r-07', ${q(code)}, ${q(name)}, 'province');`);
out.push('');
for (const f of Object.values(FIELD_LIBRARY)) out.push(`INSERT INTO field_definitions (key, def) VALUES (${q(f.key)}, ${j(f)});`);
out.push('');
CATEGORIES.forEach((c, i) =>
  out.push(
    `INSERT INTO property_categories (code, name, fields, required, filters, scoring_profile, typical_risks, legal_checks, comparable_keys, sort) VALUES (` +
      [q(c.code), j(c.name), j(c.fields), j(c.required), j(c.filters), q(c.scoringProfile), j(c.typicalRisks), j(c.legalChecks), j(c.comparableKeys), i].join(', ') +
      ');',
  ),
);
TYPES.forEach((t, i) =>
  out.push(
    `INSERT INTO property_types (code, category_code, name, financial_models, extra_fields, required, sort) VALUES (` +
      [q(t.code), q(t.category), j(t.name), j(t.financialModels), j(t.extraFields ?? []), j(t.required ?? []), i].join(', ') +
      ');',
  ),
);

writeFileSync(new URL('../migrations/0002_seed_reference.sql', import.meta.url), out.join('\n') + '\n');
console.log(`seed: ${COUNTRIES.length} countries, ${IT_REGIONS.length + LIGURIA_PROVINCES.length} regions, ${CATEGORIES.length} categories, ${TYPES.length} types`);
