import asyncio
from playwright.async_api import async_playwright
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path='/usr/bin/google-chrome', args=['--no-sandbox'])
        ctx = await b.new_context(viewport={'width': 390, 'height': 844}, device_scale_factor=2, locale='ru-RU')
        page = await ctx.new_page()
        errs=[]
        page.on('console', lambda m: errs.append(('console', m.text)) if m.type == 'error' else None)
        page.on('response', lambda r: errs.append(('RESP', r.status, r.url)) if r.status >= 400 else None)
        cdp = await ctx.new_cdp_session(page)
        await cdp.send('WebAuthn.enable')
        await cdp.send('WebAuthn.addVirtualAuthenticator', {'options': {'protocol': 'ctap2', 'transport': 'internal', 'hasResidentKey': True, 'hasUserVerification': True, 'isUserVerified': True}})
        await page.goto('http://localhost:8787')
        await page.wait_for_selector('text=Первый вход')
        await page.fill('input[autocomplete=name]', 'Батя')
        await page.fill('input[autocomplete=one-time-code]', 'test-code-1')
        await page.click('text=Создать вход по отпечатку')
        await page.wait_for_selector('text=Здравствуйте, Батя', timeout=15000)
        await page.goto('http://localhost:8787/#/calc?type=apartment&price=200000&rent=800')
        await page.wait_for_selector('text=Правила')
        await page.locator('label:has-text("Кадастровая рента") input').fill('900')
        await page.screenshot(path='/tmp/e2e/40-calc-tax.png', full_page=True)
        await page.click('button:has-text("Посчитать")')
        await page.wait_for_selector('text=Налоги Италии', timeout=15000)
        await page.screenshot(path='/tmp/e2e/41-calc-result.png', full_page=True)
        print((await page.inner_text('#result'))[:2500])
        await page.goto('http://localhost:8787/#/more')
        await page.wait_for_selector('text=Налоги в оценке объектов')
        await page.select_option('select:near(:text("Налог с аренды"))', 'short_first')
        await page.wait_for_selector('text=Сохранено.')
        await page.screenshot(path='/tmp/e2e/42-more-tax.png', full_page=True)
        print('ERRS', errs)
        await b.close()
asyncio.run(main())
